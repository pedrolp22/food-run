Mesh makeSpriteMesh(const Texture& texture) {
    const auto geometry = assets::extrudeSprite(texture.alphaMask(), texture.size().width, texture.size().height);
    if (geometry.vertices.empty()) {
        return {};
    }
    return Mesh(geometry.vertices, assets::SpriteGeometry::stride, {{0, 3, 0}, {1, 2, 3}, {2, 3, 5}}, geometry.indices);
}

